#!/usr/bin/env python3
"""Concatenate user-facing docs into one LLM context bundle."""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS = ROOT / "docs"
OUT = DOCS / "llm" / "django-grid-view-llm-context.md"

# Order matches site nav (excludes llm/* and dev/*).
SOURCES: list[Path] = [
    DOCS / "index.md",
    DOCS / "getting-started.md",
    DOCS / "simple-table.md",
    DOCS / "ag-grid.md",
    DOCS / "charts-and-kpis.md",
    DOCS / "grid-view-artifacts.md",
    DOCS / "preferences.md",
    DOCS / "architecture.md",
    DOCS / "reference" / "template-tags.md",
    DOCS / "reference" / "javascript.md",
    DOCS / "reference" / "grid-view-spec.md",
    DOCS / "reference" / "python-types.md",
    DOCS / "guides" / "chat-visualizer.md",
    DOCS / "guides" / "dashboard-builders.md",
    DOCS / "guides" / "host-app-page-export.md",
    DOCS / "guides" / "server-filtering-contract.md",
    DOCS / "guides" / "pdf-export.md",
    DOCS / "guides" / "xlsx-export.md",
    DOCS / "guides" / "i18n.md",
    DOCS / "changelog.md",
]

HEADER = """\
# django-grid-view — LLM context bundle

> Auto-generated by `scripts/build_llm_context.py`. Do not edit by hand.
> Regenerate: `uv run python scripts/build_llm_context.py`

Package: **django-grid-view** (PyPI) · Module: **django_grid_view** · Docs: https://alpiua.github.io/django-grid-view/

---

"""

_RAW_RE = re.compile(r"^\{%\s*raw\s*%\}\s*\n?|\n?\{%\s*endraw\s*%\}\s*$", re.MULTILINE)


def _strip_raw_wrapper(text: str) -> str:
    text = _RAW_RE.sub("", text)
    return text.strip() + "\n"


def _rel_link_fix(text: str, source: Path) -> str:
    """Flatten relative .md links to section paths for offline reading."""

    def repl(match: re.Match[str]) -> str:
        label, target = match.group(1), match.group(2)
        if target.startswith("http") or target.startswith("#"):
            return match.group(0)
        if target.endswith(".md"):
            try:
                rel = (source.parent / target).resolve().relative_to(DOCS.resolve())
            except ValueError:
                return match.group(0)
            return f"{label} (see section: {rel})"
        return match.group(0)

    return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", repl, text)


def build() -> str:
    parts = [HEADER]
    for path in SOURCES:
        if not path.is_file():
            raise FileNotFoundError(path)
        body = _strip_raw_wrapper(path.read_text(encoding="utf-8"))
        body = _rel_link_fix(body, path)
        rel = path.relative_to(DOCS)
        parts.append(f"\n\n<!-- source: {rel} -->\n\n")
        parts.append(body)
        parts.append("\n\n---\n")
    return "".join(parts)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"Wrote {OUT} ({OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
